/// Βοηθητικές συναρτήσεις για σύγκριση τηλεφωνικών αριθμών.
///
/// Το πρόβλημα: το call log της συσκευής (ειδικά σε Samsung/One UI)
/// συχνά αποθηκεύει τον αριθμό σε διαφορετική μορφή απ' ό,τι είναι
/// αποθηκευμένος στις Επαφές — π.χ. "+306912345678" έναντι
/// "6912345678" ή "69 1234 5678". Ένα άμεσο string comparison ποτέ δεν
/// θα ταιριάξει αυτές τις μορφές, γι' αυτό δεν εμφανιζόταν το όνομα.
///
/// Η λύση: κρατάμε μόνο τα τελευταία 9 ψηφία (αρκετά για να
/// αναγνωρίσουν μοναδικά έναν ελληνικό αριθμό κινητού/σταθερού) αφού
/// πρώτα αφαιρέσουμε οτιδήποτε δεν είναι ψηφίο.
String normalizedPhoneKey(String raw) {
  final digitsOnly = raw.replaceAll(RegExp(r'[^0-9]'), '');
  if (digitsOnly.length <= 9) return digitsOnly;
  return digitsOnly.substring(digitsOnly.length - 9);
}
